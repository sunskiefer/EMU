#!/usr/bin/env python3
"""EMU: one spec per plugin -> params.json, layout.conf and spec_keys.h (the engine's parameter table).

    gen_emu.py <plugin>/spec.py

The spec is the single place that says what every control is and where it sits (cx, cy). Moving a control is a one-line
edit of its cx/cy here, then regenerate. Parameter order = VST index; only ever append (params.lock).
Standing L'Cronx rules applied here: Meta4 text sizes (scale_names=1, label_scale=1.7), overview tiles + OVERVIEW and < >
in the header, one Q-Link set (ql1..ql16) that follows the page on screen.
"""
import json, os, re, runpy, sys

here = os.path.dirname(os.path.abspath(sys.argv[1]))
S = runpy.run_path(sys.argv[1])["SPEC"]
pages = S["pages"]                      # [(title, [(note)])]
C = S["controls"]                       # list of dicts
for _c in C: _c.setdefault("page", 1)

ART = S.get("art")                      # {"scale":1.2511,"x":37,"y":0}: spec x,y are pixels of the art image
def lx(c): return round(ART["x"] + c["x"] * ART["scale"]) if ART and "x" in c else c["cx"]
def ly(c): return round(ART["y"] + c["y"] * ART["scale"] + 86) if ART and "y" in c else c["cy"]
def lr(c): return c["r"] if "r" in c else (round(c["ir"] * ART["scale"]) if ART and "ir" in c else 48)

def cid(k): return re.sub(r"\W", "_", k).upper()

params = []
for c in C:
    p = {"key": c["key"], "name": c["name"]}
    kind = c["kind"]
    if kind in ("knob", "slider"):
        p.update(min=c.get("min", 0), max=c.get("max", 10), default=c.get("default", 5))
    elif kind in ("enum_h", "enum_v", "toggle", "popup"):
        p.update(options=c["options"], default=c.get("default", 0))
    elif kind == "button":
        p.update(min=0, max=1, momentary=True)
    elif kind == "readout":
        p.update(min=0, max=1, type="readout", display="string")
    if c.get("int"): p["display"] = "int"
    params.append(p)
n_ctrl = len(params)
ONE = bool(S.get("onepage"))
if not ONE:
  params.append({"key": "view", "name": "View", "options": ["Overview"] + [t for t, _ in pages], "default": 0})
  params.append({"key": "in_sec", "name": "In Section", "options": ["Overview", "Section"], "default": 0})
  for k, n in (("nav_zoom", "OVERVIEW"), ("nav_prev", "<"), ("nav_next", ">")):
    params.append({"key": k, "name": n, "min": 0, "max": 1, "momentary": True, "type": "trigger", "refresh_display": True})
  for i, (t, _) in enumerate(pages, 1):
    params.append({"key": "go_%d" % i, "name": "Go " + t, "min": 0, "max": 1, "momentary": True, "type": "trigger", "refresh_display": True})
for i in range(1, 17):
    params.append({"key": "ql%d" % i, "name": "Q-Link %d" % i, "min": 0, "max": 1, "default": 0, "dynamic_name": True, "dynamic_display": True})
json.dump({"name": S["name"], "params": params}, open(os.path.join(here, "params.json"), "w"), indent=1)

# ---- layout.conf
L = ["# %s page layout. GENERATED by tools/gen_emu.py from spec.py -- edit spec.py (cx, cy, r), not this." % S["name"],
     "# One page over the plugin's own panel art (ONE page, no tiles). Controls sit at their art positions.",
     "scale_names=1", "label_scale=1.7"]
th = S.get("theme", {"bg": "1a1a1a", "panel": "1a1a1a", "line": "bfbfbf", "ink": "f2f2f2", "ink_dim": "c8c8c8", "ink_faint": "7a7a7a",
      "accent": "f07a1e", "accent_hi": "ffffff", "knob_face": "151515", "knob_ring": "3c3c3c", "knob_dot": "f2f2f2", "bar": "101010",
      "seg_active": "f07a1e", "seg_inactive": "151515", "seg_active_tx": "111111", "btn_text": "f2f2f2", "tab_on": "f07a1e",
      "tab_on_tx": "111111", "lcd": "101010", "box": "151515"})
for k, v in th.items(): L.append("theme_%s=%s" % (k, v))
L.append("qlinks_track = " + ",".join("ql%d" % i for i in range(1, 17)))
L.append("")
L.append("[tab %s]" % S["name"])
if not ONE:
    L.append('button cx=120 cy=124 label="OVERVIEW" key=nav_zoom bw=220 when=in_sec:1')
    L.append('button cx=340 cy=124 label="<" key=nav_prev bw=120 when=in_sec:1')
    L.append('button cx=480 cy=124 label=">" key=nav_next bw=120 when=in_sec:1')
    tiles = S.get("tiles")
    if not tiles:
        n = len(pages); cols = 3 if n > 4 else 2 if n > 2 else n; rows = (n + cols - 1) // cols
        tw, tht = 380, 190
        tiles = []
        for i in range(n):
            cx = 640 + (i % cols - (cols - 1) / 2) * (tw + 30); cy = 370 + (i // cols - (rows - 1) / 2) * (tht + 30)
            tiles.append((round(cx), round(cy)))
    for i, ((t, _), (cx, cy)) in enumerate(zip(pages, tiles), 1):
        L.append('button cx=%d cy=%d label="%s" key=go_%d bw=360 bh=170 when=view:0' % (cx, cy, t, i))
for c in C:
    pg = c["page"]
    parts = [c["kind"], "cx=%d" % lx(c), "cy=%d" % ly(c)]
    k = c["kind"]
    if k == "knob": parts.append("r=%d" % lr(c))
    if k == "knob" and ONE: parts += ["ns=0", "vs=0"]
    if k in ("readout", "popup", "slider_h"): parts += ["w=%d" % c.get("w", 300), "h=%d" % c.get("h", 56)]
    if k in ("enum_h", "enum_v"):
        parts += ["sw=%d" % c.get("sw", 130), "sh=%d" % c.get("sh", 60), "rows=%d" % c.get("rows", 1)]
    parts.append('label="%s"' % c.get("label", "" if k == "readout" else c["name"]))
    parts.append("key=%s" % c["key"])
    if k in ("knob", "toggle"): parts += ["bw=%d" % c.get("bw", 170)]
    if k == "toggle" and ONE: parts += ["ns=0"]
    if k == "button": parts += ["bw=%d" % c.get("bw", 130)] + (["bh=%d" % c["bh"]] if "bh" in c else [])
    if k == "readout" and c.get("tsize"): parts += ["tsize=%d" % c["tsize"], "talign=%s" % c.get("talign", "center")]
    if k in ("enum_h", "enum_v"): parts.append('options="%s"' % ",".join(o.upper() for o in c["options"]))
    if not ONE: parts.append("when=view:%d" % pg)
    L.append(" ".join(parts))
L.append('qlinks "%s" = %s' % (S["name"], ",".join("ql%d" % i for i in range(1, 17))))
open(os.path.join(here, "layout.conf"), "w").write("\n".join(L) + "\n")

# ---- spec_keys.h for the engine
H = ["// GENERATED by tools/gen_emu.py from spec.py -- do not edit.", "#pragma once", "#include <cstddef>", "enum {"]
for p in params: H.append("\tP_%s," % cid(p["key"]))
H.append("\tP_COUNT\n};")
H.append("static const char *const kKeys[P_COUNT] = {" + ",".join('"%s"' % p["key"] for p in params) + "};")
H.append("static const char *const kNames[P_COUNT] = {" + ",".join('"%s"' % p["name"] for p in params) + "};")
H.append("enum { N_CTRL = %d, N_PAGES = %d };" % (n_ctrl, len(pages)))
H.append("static const char *const kPageTitles[N_PAGES] = {" + ",".join('"%s"' % t for t, _ in pages) + "};")
H.append("// Q-Link set per page: the parameter index each of ql1..ql16 drives (-1 = none). Page 0 is the overview.")
ql = [[-1] * 16 for _ in range(len(pages) + 1)]
for c in C: c.setdefault('page', 1)
idx = {c["key"]: i for i, c in enumerate(C)}
for pi in range(1, len(pages) + 1):
    keys = [c["key"] for c in C if c["page"] == pi and c.get("ql", c["kind"] in ("knob", "slider", "toggle", "enum_h", "enum_v", "popup"))]
    for j, k in enumerate(keys[:16]): ql[pi][j] = idx[k]
H.append("static const int kQl[N_PAGES + 1][16] = {" + ",".join("{" + ",".join(str(x) for x in r) + "}" for r in ql) + "};")
H.append("// parameter ranges: kMin, kMax, kDef (options count in kMax)")
H.append("static const double kMin[P_COUNT] = {" + ",".join(str(p.get("min", 0)) for p in params) + "};")
H.append("static const double kMax[P_COUNT] = {" + ",".join(str(p["max"] if "max" in p else len(p["options"]) - 1) for p in params) + "};")
H.append("static const double kDef[P_COUNT] = {" + ",".join(str(p.get("default", 0)) for p in params) + "};")
H.append("// option names ('|' separated) for option parameters, empty otherwise")
H.append("static const char *const kOpts[P_COUNT] = {" + ",".join('"%s"' % "|".join(p.get("options", [])) for p in params) + "};")
open(os.path.join(here, "spec_keys.h"), "w").write("\n".join(H) + "\n")
print("%s: %d params (%d controls), %d pages" % (S["name"], len(params), n_ctrl, len(pages)))
